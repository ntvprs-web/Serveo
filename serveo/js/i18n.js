// Current active language (stored in localStorage)
export function getActiveLanguage() {
  try {
    return localStorage.getItem('serveo_language') || 'en';
  } catch (e) {
    return 'en';
  }
}

export function setActiveLanguage(lang) {
  if (!INDIAN_LANGUAGES[lang]) lang = 'en';
  try {
    localStorage.setItem('serveo_language', lang);
  } catch (e) {}
  applyTranslations(lang);
}

// Translate all data-i18n elements on the page
export function applyTranslations(lang = getActiveLanguage()) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

  // Update text for all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Update input placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Update category filter chips dynamically if they exist on page
  document.querySelectorAll('.filter-chip[data-category]').forEach(chip => {
    const cat = chip.getAttribute('data-category');
    if (cat === 'all' && dict.filter_all) {
      chip.textContent = dict.filter_all;
    } else if (dict['cat_' + cat]) {
      const emoji = chip.textContent.split(' ')[0] || '';
      chip.textContent = `${emoji} ${dict['cat_' + cat]}`;
    }
  });

  // Update select dropdown for language
  const select = document.getElementById('serveo-lang-select');
  if (select && select.value !== lang) {
    select.value = lang;
  }
}

// Generate the Language Selector dropdown HTML for Navbar
export function getLanguageSelectorHTML() {
  const currentLang = getActiveLanguage();
  const options = Object.entries(INDIAN_LANGUAGES).map(([code, data]) => {
    return `<option value="${code}" ${code === currentLang ? 'selected' : ''}>${data.flag} ${data.native} (${data.name})</option>`;
  }).join('');

  return `
    <div class="lang-selector-wrap">
      <select id="serveo-lang-select" class="lang-select" title="Choose Indian Language">
        ${options}
      </select>
    </div>
  `;
}

// Wire up language switcher change event
export function initLanguageSupport() {
  applyTranslations();

  document.addEventListener('change', (e) => {
    if (e.target.id === 'serveo-lang-select') {
      const selected = e.target.value;
      setActiveLanguage(selected);
      showToast(`Language changed to ${INDIAN_LANGUAGES[selected]?.native || selected}`, 'success');
    }
  });
}

// Auto init on DOM ready
if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initLanguageSupport);
  } else {
    initLanguageSupport();
  }
}
